import type { Metadata } from "next"
import { personalInfo, socialLinks } from "@/lib/data"

/** Production URL used for canonical links, the sitemap and social previews. Override with NEXT_PUBLIC_SITE_URL. */
export const siteUrl = (process.env.NEXT_PUBLIC_SITE_URL || "https://imranelabrahimi.me").replace(/\/+$/, "")

export const siteName = personalInfo.name

export const defaultTitle = `${personalInfo.name} | ${personalInfo.title}`

export const defaultDescription = `${personalInfo.name}, full-stack web developer in Casablanca, Morocco: ${personalInfo.yearsOfExperience} years building custom WordPress websites and web applications. Open to freelance and full-time roles.`

/** X handle derived from the profile URL in lib/data.ts, e.g. "@Imrane_II". */
export const xHandle = socialLinks.x ? `@${socialLinks.x.replace(/\/+$/, "").split("/").pop()}` : undefined

/** Share card generated by app/opengraph-image.tsx (child pages must reference it explicitly). */
const shareImage = {
  url: "/opengraph-image",
  width: 1200,
  height: 630,
  alt: `${personalInfo.name}, ${personalInfo.title}`,
}

interface PageMetadataOptions {
  /** Short page title; the root layout's template appends the site name. */
  title?: string
  description: string
  /** Path of the page, e.g. "/about". */
  path: string
}

/**
 * Per-page metadata with canonical URL, Open Graph and X/Twitter tags.
 * Open Graph and Twitter objects replace (not merge with) the layout's, so they are rebuilt here in full.
 * That also drops the root's file-based share image, so it is referenced explicitly.
 */
export function pageMetadata({ title, description, path }: PageMetadataOptions): Metadata {
  const fullTitle = title ? `${title} | ${siteName}` : defaultTitle

  return {
    ...(title ? { title } : { title: { absolute: defaultTitle } }),
    description,
    alternates: { canonical: path },
    openGraph: {
      type: "website",
      locale: "en_US",
      siteName,
      url: path,
      title: fullTitle,
      description,
      images: [shareImage],
    },
    twitter: {
      card: "summary_large_image",
      creator: xHandle,
      title: fullTitle,
      description,
      images: ["/twitter-image"],
    },
  }
}
